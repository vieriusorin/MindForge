import YAML from "yaml";
import type { Dropped, GeneratedBy, ItemKind } from "./types";

/** MF-0014 GOAL "Decided": one card and one diagram per skill. */
export const ITEMS_PER_SKILL = 1;

const FILE_KEY = {
  card: "cards",
  diagram: "diagrams",
} as const satisfies Record<ItemKind, string>;

/** The draft's sources that the skill does not list in `pack.yaml`. */
export function foreignSources(
  sources: readonly string[],
  sourceUrls: readonly string[],
): string[] {
  return sources.filter((url) => !sourceUrls.includes(url));
}

/**
 * MF-0014 SC-3, SC-4, SC-8: one card or diagram file for a skill. Provenance (`id`, `origin`,
 * `author`, `generatedBy`, `skill`) comes from code; `body` supplies only the model's fields.
 * At most one item is written; the rest are listed with a reason.
 */
export function renderItemFile<D>({
  kind,
  packSlug,
  skill,
  runTag,
  drafts,
  author,
  generatedBy,
  rejectReason,
  body,
}: {
  kind: ItemKind;
  packSlug: string;
  skill: string;
  runTag: string;
  drafts: D[];
  author: string;
  generatedBy: GeneratedBy;
  rejectReason: (draft: D) => string | null;
  body: (draft: D) => Record<string, unknown>;
}): { text: string; written: number; dropped: Dropped[] } {
  if (!/^[a-z0-9-]+$/.test(runTag))
    throw new Error(`renderItemFile: runTag "${runTag}" must be [a-z0-9-]`);
  const items: Record<string, unknown>[] = [];
  const dropped: Dropped[] = [];
  drafts.forEach((draft, index) => {
    const reason =
      items.length >= ITEMS_PER_SKILL
        ? "over the skill's need"
        : rejectReason(draft);
    if (reason) {
      dropped.push({ index, reason });
      return;
    }
    items.push({
      id: `${packSlug}.${skill}.${kind}-${runTag}-${items.length + 1}`,
      origin: "ai",
      author,
      generatedBy: { model: generatedBy.model, prompt: generatedBy.prompt },
      ...body(draft),
    });
  });
  const header = `# MF-0014: generated by ${generatedBy.model} (${generatedBy.prompt}), run ${runTag}. Review in-app before trusting.\n`;
  return {
    text: header + YAML.stringify({ skill, [FILE_KEY[kind]]: items }),
    written: items.length,
    dropped,
  };
}
