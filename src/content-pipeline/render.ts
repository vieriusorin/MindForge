import YAML from "yaml";
import { z } from "zod";
import type { Draft, Dropped, GeneratedBy } from "./types";

const Email = z.email();

/** SC-3: the runner's sign-in email (CONTEXT.md Author). Required: a wrong one lets authors approve their own items. */
export function authorEmail(env: Record<string, string | undefined>): string {
  const parsed = Email.safeParse(env.MF_AUTHOR_EMAIL?.trim());
  if (!parsed.success)
    throw new Error(
      "Set MF_AUTHOR_EMAIL to the email you sign in to MindForge with (it becomes `author` on every item).",
    );
  return parsed.data;
}

/** Why a draft is not written, or null when it may be. */
function rejectReason(
  draft: Draft,
  sourceUrls: readonly string[],
): string | null {
  if (!sourceUrls.includes(draft.citation.url))
    return "citation is not one of the skill's sources";
  if (draft.options.some((o) => o.rationale.trim().length === 0))
    return "an option has no rationale";
  if (!draft.options.some((o) => o.correct)) return "no correct option";
  if (new Set(draft.options.map((o) => o.id)).size !== draft.options.length)
    return "duplicate option id";
  return null;
}

/**
 * SC-3, SC-7: one questions file for a skill. Provenance (`id`, `origin`, `author`, `generatedBy`,
 * `skill`) and `select` come from code; the model supplies only stem, options and citation.
 * At most `need` drafts are written; the rest are listed with a reason.
 */
export function renderQuestionFile({
  packSlug,
  skill,
  runTag,
  drafts,
  author,
  generatedBy,
  sourceUrls,
  need,
}: {
  packSlug: string;
  skill: string;
  runTag: string;
  drafts: Draft[];
  author: string;
  generatedBy: GeneratedBy;
  sourceUrls: string[];
  need: number;
}): { text: string; written: number; dropped: Dropped[] } {
  if (!/^[a-z0-9-]+$/.test(runTag))
    throw new Error(`renderQuestionFile: runTag "${runTag}" must be [a-z0-9-]`);
  const questions: Record<string, unknown>[] = [];
  const dropped: Dropped[] = [];
  drafts.forEach((draft, index) => {
    const reason =
      questions.length >= need
        ? "over the skill's need"
        : rejectReason(draft, sourceUrls);
    if (reason) {
      dropped.push({ index, reason });
      return;
    }
    questions.push({
      id: `${packSlug}.${skill}.${runTag}-${questions.length + 1}`,
      origin: "ai",
      author,
      generatedBy: { model: generatedBy.model, prompt: generatedBy.prompt },
      stem: draft.stem.trim(),
      select: draft.options.filter((o) => o.correct).length,
      options: draft.options.map((o) => ({
        id: o.id,
        text: o.text.trim(),
        correct: o.correct,
        rationale: o.rationale.trim(),
      })),
      source: { title: draft.citation.title.trim(), url: draft.citation.url },
    });
  });
  const header = `# MF-0008: generated by ${generatedBy.model} (${generatedBy.prompt}), run ${runTag}. Review in-app before trusting.\n`;
  return {
    text: header + YAML.stringify({ skill, questions }),
    written: questions.length,
    dropped,
  };
}
